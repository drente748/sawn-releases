package com.sawn.app.ads

/**
 * بنية الإعلانات — معطلة بالكامل في 2.0.0.
 *
 * النموذج المستقبلي (كما قرّره المالك):
 *   - المشتركون في النسخة المدفوعة: لا إعلانات أبدًا.
 *   - غير المشتركين (Free tier): إعلانات من شبكات إعلانية للجوال (Google Mobile Ads أو ما يعادله).
 *
 * ما لا يوجد الآن في هذه النسخة:
 *   - لا SDK مضافة، لا معرف تطبيق إعلاني، لا banners، لا تحميل موارد، لا اتصال.
 *   - دور [AdsController] هو "لا تفعل شيئًا"؛ تُفعَّل فقط حين يبني الإصدار المدعوم بالإعلانات.
 *
 * خطة التفعيل (موثقة لـ PLAY_COMPLIANCE):
 *   1. تحديث docs/privacy.md قبلًا (المعرفات + الغرض + الاحتفاظ بالبيانات).
 *   2. إضافة SDK مختارة + App ID + شاشة "إزالة الإعلانات" مرتبطة بالدفع.
 *   3. تصريح Play Console: "يحتوي على إعلانات" + Data Safety بنفس يوم الإطلاق.
 *   4. زر واضح في الإعدادات: إزالة الإعلانات ← الدفع.
 */

enum class AdSlot {
    /** بانر أسفل الرئيسية — المكان الوحيد المخطط حاليًا (يختفي مع الاشتراك). */
    HOME_BANNER,
}

/** عقد الإعلان — معاد اليوم دائمًا. */
interface AdsController {
    /** true فقط للـ Free tier في إصدار مدعومة بالإعلانات. الحالي: false دائمًا. */
    fun isEnabled(slot: AdSlot): Boolean
}

/** تنفيذ 2.0.0: صامت تمامًا — لا إعلان لأي مستخدم. */
object NoopAdsController : AdsController {
    override fun isEnabled(slot: AdSlot): Boolean = false
}
